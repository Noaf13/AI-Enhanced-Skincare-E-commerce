/**
 * Root Layout Component
 *
 * Main application layout that wraps all pages with essential providers and global components.
 * Sets up font configuration, global state management, authentication, and UI utilities.
 *
 * @file app/layout.tsx
 * @component RootLayout
 *
 * @example
 * // Automatically applied to all pages in the app router
 * // Provides global context, authentication, and toast notifications
 *
 * @features
 * - Global font configuration with Geist font family
 * - Clerk authentication provider
 * - Shopping cart state management
 * - Toast notification system
 * - Cart popup modal
 * - Global CSS styles
 *
 * @providers
 * - ClerkProvider: Authentication and user management
 * - StateContext: Shopping cart and application state
 * - Toaster: Notification toast system
 *
 * @components
 * - CartPopup: Shopping cart sidebar modal
 *
 * @dependencies
 * - next/font: Font optimization
 * - @clerk/nextjs: Authentication
 * - react-hot-toast: Notifications
 * - context/StateContext: Global state
 */
// app/layout.tsx
import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { StateContext } from "../context/StateContext";
import { Toaster } from "react-hot-toast";
import CartPopup from "../components/CartPopUp";
import { ClerkProvider } from "@clerk/nextjs";
import ChatContainer from '@/components/chat/ChatContainer';


const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

/**
 * RootLayout Component
 *
 * Main layout wrapper for the entire application. Provides global providers,
 * fonts, and components that should be available on every page.
 *
 * @param {Object} props - Component properties
 * @param {React.ReactNode} props.children - Child pages/components to render
 * @returns {JSX.Element} Wrapped application with global providers
 *
 * @note This is a server component by default in Next.js App Router
 */

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    // Clerk authentication provider wraps entire app for user management and authentication
    <ClerkProvider>
  <html lang="en">
    <body className={`${geistSans.variable} ${geistMono.variable} antialiased`}>
      <StateContext>
        <ChatContainer />
        {children}
        <CartPopup />
        <Toaster
          position="bottom-right"
          toastOptions={{
            duration: 3000,
            style: {
              background: "#363636",
              color: "#fff",
            },
          }}
        />
      </StateContext>
    </body>
  </html>
</ClerkProvider>
  );
}
